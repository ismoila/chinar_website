def _bool(nom, sukut="False"):
    """.env dagi True/False qiymatini o'qiydi"""
    return str(os.getenv(nom, sukut)).strip().lower() in ("1", "true", "yes", "ha")


def _royxat(nom, sukut=""):
    """.env dagi vergul bilan ajratilgan ro'yxatni o'qiydi"""
    return [x.strip() for x in os.getenv(nom, sukut).split(",") if x.strip()]


